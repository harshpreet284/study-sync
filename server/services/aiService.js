import mongoose from 'mongoose';
import { Resource } from '../models/Resource.js';
import { LearningProgress } from '../models/LearningProgress.js';

// Constants
export const MAX_PLAN_WEEKS = 12;
export const MAX_RESOURCES_PER_WEEK = 5;
export const MAX_TASKS_PER_WEEK = 10;
export const GROQ_COMPLETIONS_URL = 'https://api.groq.com/openai/v1/chat/completions';
export const DEFAULT_GROQ_MODEL = 'openai/gpt-oss-20b';

/**
 * Escapes characters with special meaning in regular expressions.
 * @param {string} str
 * @returns {string}
 */
const escapeRegex = (str) => {
  if (typeof str !== 'string') return '';
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
};

/**
 * Matches catalog resources against goal target skills.
 *
 * @param {object} goal - LearningGoal document
 * @returns {Promise<Array<object>>} Matching candidate resources
 */
export const findCandidateResources = async (goal) => {
  if (!goal || !Array.isArray(goal.targetSkills) || goal.targetSkills.length === 0) {
    return [];
  }

  const cleanSkills = goal.targetSkills
    .map((s) => (typeof s === 'string' ? s.trim() : ''))
    .filter((s) => s.length > 0);

  if (cleanSkills.length === 0) {
    return [];
  }

  // Construct case-insensitive exact match regex queries for skills array
  const skillQueries = cleanSkills.map((skill) => ({
    skills: { $regex: `^${escapeRegex(skill)}$`, $options: 'i' },
  }));

  // Find up to 15 matching resources, bounded, relevant, and deterministically sorted
  const candidateResources = await Resource.find({ $or: skillQueries })
    .select('_id title type difficulty estimatedDuration skills category modules createdAt')
    .sort({ createdAt: -1, _id: 1 })
    .limit(15);

  return candidateResources;
};

/**
 * Retrieves user learning progress records for candidate resources.
 *
 * @param {string|mongoose.Types.ObjectId} userId
 * @param {Array<object>} candidateResources
 * @returns {Promise<Map<string, string>>} Map of resourceId -> status
 */
export const getCandidateProgressMap = async (userId, candidateResources) => {
  if (!userId || !Array.isArray(candidateResources) || candidateResources.length === 0) {
    return new Map();
  }

  const resourceIds = candidateResources.map((r) => r._id);
  const progressRecords = await LearningProgress.find({
    user: userId,
    resource: { $in: resourceIds },
  }).select('resource status progress');

  const progressMap = new Map();
  for (const record of progressRecords) {
    progressMap.set(record.resource.toString(), record.status);
  }

  return progressMap;
};

/**
 * Validates and sanitizes plan weeks generated by AI (or mock).
 *
 * Ensures:
 * - Sequential weekNumber starting at 1
 * - Non-empty string focus (3-250 chars)
 * - Non-empty array of string tasks (1-10 tasks, 3-300 chars each)
 * - Every referenced resource belongs to the vetted candidate set
 * - Maximum plan duration bounded to MAX_PLAN_WEEKS (12 weeks)
 *
 * @param {Array<object>} rawWeeks - Unvalidated weeks from AI
 * @param {Array<object>} candidateResources - Curated candidate resources
 * @returns {Array<object>} Validated and sanitized weeks
 */
export const validateAndSanitizeWeeks = (rawWeeks, candidateResources) => {
  if (!Array.isArray(rawWeeks) || rawWeeks.length === 0) {
    const error = new Error('AI plan generation failed: Plan must contain at least one week.');
    error.statusCode = 422;
    throw error;
  }

  if (rawWeeks.length > MAX_PLAN_WEEKS) {
    const error = new Error(`AI plan generation failed: Plan duration cannot exceed ${MAX_PLAN_WEEKS} weeks.`);
    error.statusCode = 422;
    throw error;
  }

  // Create lookup set of valid candidate ObjectIds as strings
  const validCandidateIdMap = new Map();
  for (const res of candidateResources) {
    validCandidateIdMap.set(res._id.toString(), res._id);
  }

  const validatedWeeks = [];

  for (let idx = 0; idx < rawWeeks.length; idx++) {
    const week = rawWeeks[idx];
    const expectedWeekNumber = idx + 1;

    if (!week || typeof week !== 'object') {
      const error = new Error(`AI plan validation error: Week ${expectedWeekNumber} is invalid.`);
      error.statusCode = 422;
      throw error;
    }

    if (week.weekNumber !== expectedWeekNumber) {
      const error = new Error(
        `AI plan validation error: Week numbers must be sequential starting at 1. Expected ${expectedWeekNumber}, got ${week.weekNumber}.`
      );
      error.statusCode = 422;
      throw error;
    }

    if (typeof week.focus !== 'string' || week.focus.trim().length < 3 || week.focus.trim().length > 250) {
      const error = new Error(
        `AI plan validation error: Week ${expectedWeekNumber} focus must be between 3 and 250 characters.`
      );
      error.statusCode = 422;
      throw error;
    }

    // Validate tasks
    if (!Array.isArray(week.tasks) || week.tasks.length === 0) {
      const error = new Error(`AI plan validation error: Week ${expectedWeekNumber} must contain at least one task.`);
      error.statusCode = 422;
      throw error;
    }

    if (week.tasks.length > MAX_TASKS_PER_WEEK) {
      const error = new Error(
        `AI plan validation error: Week ${expectedWeekNumber} cannot exceed ${MAX_TASKS_PER_WEEK} tasks.`
      );
      error.statusCode = 422;
      throw error;
    }

    const cleanTasks = [];
    for (const task of week.tasks) {
      if (typeof task !== 'string' || task.trim().length < 3 || task.trim().length > 300) {
        const error = new Error(
          `AI plan validation error: Tasks in Week ${expectedWeekNumber} must be between 3 and 300 characters.`
        );
        error.statusCode = 422;
        throw error;
      }
      cleanTasks.push(task.trim());
    }

    // Validate resource references (accepts resourceIds or resources array of IDs)
    const rawResourceIds = week.resourceIds || week.resources || [];
    if (!Array.isArray(rawResourceIds)) {
      const error = new Error(`AI plan validation error: Resources in Week ${expectedWeekNumber} must be an array.`);
      error.statusCode = 422;
      throw error;
    }

    if (rawResourceIds.length > MAX_RESOURCES_PER_WEEK) {
      const error = new Error(
        `AI plan validation error: Week ${expectedWeekNumber} cannot reference more than ${MAX_RESOURCES_PER_WEEK} resources.`
      );
      error.statusCode = 422;
      throw error;
    }

    const cleanResourceIds = [];
    const seenIdsInWeek = new Set();

    for (const rawId of rawResourceIds) {
      const idStr = (typeof rawId === 'object' && rawId?._id ? rawId._id : rawId)?.toString()?.trim();
      if (!idStr || !mongoose.Types.ObjectId.isValid(idStr)) {
        const error = new Error(
          `AI plan validation error: Week ${expectedWeekNumber} references an invalid resource ID format.`
        );
        error.statusCode = 422;
        throw error;
      }

      // CRITICAL SECURITY ENFORCEMENT: Reject any model-invented or non-candidate resource reference
      if (!validCandidateIdMap.has(idStr)) {
        const error = new Error(
          `AI plan validation error: Week ${expectedWeekNumber} references resource '${idStr}' which is not in the approved catalog candidates.`
        );
        error.statusCode = 422;
        throw error;
      }

      if (!seenIdsInWeek.has(idStr)) {
        seenIdsInWeek.add(idStr);
        cleanResourceIds.push(validCandidateIdMap.get(idStr));
      }
    }

    validatedWeeks.push({
      weekNumber: expectedWeekNumber,
      focus: week.focus.trim(),
      resources: cleanResourceIds,
      tasks: cleanTasks,
    });
  }

  return validatedWeeks;
};

/**
 * Deterministic mock planner for automated testing and offline development.
 * Never makes external network requests and relies strictly on validated inputs.
 *
 * @param {object} params
 * @param {object} params.goal - LearningGoal document
 * @param {Array<object>} params.candidateResources - Vetted candidate resources
 * @param {Map<string, string>} [params.progressMap] - User progress lookup
 * @returns {object} Structured plan with weeks array
 */
export const generateDeterministicMockPlan = ({ goal, candidateResources, progressMap = new Map() }) => {
  if (!candidateResources || candidateResources.length === 0) {
    const error = new Error('No candidate resources available for mock plan generation.');
    error.statusCode = 400;
    throw error;
  }

  // Determine duration bounded between 1 and 12 weeks
  let plannedWeeks = 4;
  if (goal.targetDate) {
    const now = Date.now();
    const targetMs = new Date(goal.targetDate).getTime();
    if (!isNaN(targetMs) && targetMs > now) {
      const diffWeeks = Math.ceil((targetMs - now) / (1000 * 60 * 60 * 24 * 7));
      plannedWeeks = Math.min(MAX_PLAN_WEEKS, Math.max(1, diffWeeks));
    }
  } else {
    plannedWeeks = Math.min(MAX_PLAN_WEEKS, Math.max(2, Math.min(6, candidateResources.length * 2)));
  }

  const rawWeeks = [];
  const candidateCount = candidateResources.length;

  for (let i = 0; i < plannedWeeks; i++) {
    const weekNumber = i + 1;
    const assignedResource = candidateResources[i % candidateCount];
    const skillName = assignedResource.skills?.[0] || goal.targetSkills?.[0] || 'Core Concepts';

    const tasks = [
      `Complete introductory modules for ${assignedResource.title}`,
      `Practice hands-on exercises focused on ${skillName}`,
      `Review key takeaways and test comprehension`,
    ];

    rawWeeks.push({
      weekNumber,
      focus: `Week ${weekNumber}: Mastering ${skillName} with ${assignedResource.title}`,
      resourceIds: [assignedResource._id.toString()],
      tasks,
    });
  }

  return { weeks: rawWeeks };
};

/**
 * JSON Schema for Groq structured outputs.
 */
export const GROQ_PLAN_JSON_SCHEMA = {
  name: 'learning_study_plan',
  strict: true,
  schema: {
    type: 'object',
    properties: {
      weeks: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            weekNumber: { type: 'integer' },
            focus: { type: 'string' },
            resourceIds: {
              type: 'array',
              items: { type: 'string' },
            },
            tasks: {
              type: 'array',
              items: { type: 'string' },
            },
          },
          required: ['weekNumber', 'focus', 'resourceIds', 'tasks'],
          additionalProperties: false,
        },
      },
    },
    required: ['weeks'],
    additionalProperties: false,
  },
};

/**
 * Calls Groq's OpenAI-compatible Chat Completions API with structured output schema.
 *
 * @param {object} params
 * @param {object} params.goal - LearningGoal document
 * @param {Array<object>} params.candidateResources - Vetted candidate resources
 * @param {Map<string, string>} params.progressMap - User progress map
 * @param {object} [options]
 * @param {number} [options.timeoutMs=15000] - Request timeout in ms
 * @returns {Promise<object>} Parsed raw AI response
 */
export const callGroqApi = async ({ goal, candidateResources, progressMap }, { timeoutMs = 15000 } = {}) => {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey || apiKey.trim() === '') {
    const error = new Error('AI provider configuration is missing on the server.');
    error.statusCode = 500;
    throw error;
  }

  const model = process.env.GROQ_MODEL || DEFAULT_GROQ_MODEL;

  // Build concise candidate metadata
  const candidateMetadata = candidateResources.map((res) => ({
    resourceId: res._id.toString(),
    title: res.title,
    type: res.type,
    difficulty: res.difficulty,
    estimatedDurationHours: res.estimatedDuration,
    skills: res.skills,
    userLibraryStatus: progressMap.get(res._id.toString()) || 'NOT_IN_LIBRARY',
  }));

  const systemPrompt =
    'You are the StudySync Curriculum Planner. You generate a structured, sequential study plan for a student based on their learning goal, target skills, weekly study hours, and available learning resources.\n' +
    'CRITICAL CONSTRAINTS:\n' +
    '1. You MUST ONLY reference resourceIds from the provided Approved Resources list. Never invent or hallucinate resource IDs.\n' +
    '2. Plan duration must be between 1 and 12 weeks.\n' +
    '3. Week numbers must start at 1 and be strictly sequential.\n' +
    '4. Provide 2-5 actionable, high-quality tasks per week.';

  const userPrompt = JSON.stringify({
    studentGoal: {
      title: goal.title,
      description: goal.description || '',
      targetSkills: goal.targetSkills,
      currentLevel: goal.currentLevel,
      weeklyHours: goal.weeklyHours,
      targetDate: goal.targetDate ? goal.targetDate.toISOString().slice(0, 10) : null,
    },
    approvedResources: candidateMetadata,
  });

  const requestBody = {
    model,
    messages: [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userPrompt },
    ],
    response_format: {
      type: 'json_schema',
      json_schema: GROQ_PLAN_JSON_SCHEMA,
    },
    temperature: 0.2,
  };

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

  try {
    const response = await fetch(GROQ_COMPLETIONS_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${apiKey.trim()}`,
      },
      body: JSON.stringify(requestBody),
      signal: controller.signal,
    });

    if (!response.ok) {
      let errorText = '';
      try {
        errorText = await response.text();
      } catch (textErr) {
        if (textErr.name === 'AbortError') {
          throw textErr;
        }
        errorText = '';
      }
      console.error(`[Groq API Error] HTTP ${response.status}: ${errorText}`);

      if (response.status === 429) {
        const error = new Error('AI provider rate limit reached. Please try again in a few moments.');
        error.statusCode = 429;
        throw error;
      }

      if (response.status >= 500) {
        const error = new Error('AI service is temporarily unavailable. Please try again later.');
        error.statusCode = 502;
        throw error;
      }

      const error = new Error('Failed to generate study plan from AI service.');
      error.statusCode = 502;
      throw error;
    }

    let json;
    try {
      json = await response.json();
    } catch (jsonErr) {
      if (jsonErr.name === 'AbortError') {
        throw jsonErr;
      }
      const error = new Error('Malformed JSON received from AI service.');
      error.statusCode = 502;
      throw error;
    }

    if (
      !json ||
      typeof json !== 'object' ||
      !Array.isArray(json.choices) ||
      json.choices.length === 0 ||
      !json.choices[0] ||
      !json.choices[0].message
    ) {
      const error = new Error('Malformed response received from AI service.');
      error.statusCode = 502;
      throw error;
    }

    const message = json.choices[0].message;

    // Detect model refusal response
    if (message.refusal) {
      const error = new Error('AI service refused to generate a study plan for this goal.');
      error.statusCode = 502;
      throw error;
    }

    const contentStr = message.content;
    if (typeof contentStr !== 'string' || contentStr.trim() === '') {
      const error = new Error('AI service returned empty or null plan content.');
      error.statusCode = 502;
      throw error;
    }

    let parsedData;
    try {
      parsedData = JSON.parse(contentStr);
    } catch {
      const error = new Error('Malformed plan JSON received from AI service.');
      error.statusCode = 502;
      throw error;
    }

    if (
      !parsedData ||
      typeof parsedData !== 'object' ||
      Array.isArray(parsedData) ||
      !Array.isArray(parsedData.weeks)
    ) {
      const error = new Error('Malformed plan structure received from AI service.');
      error.statusCode = 502;
      throw error;
    }

    return parsedData;
  } catch (err) {
    if (err.name === 'AbortError') {
      const error = new Error('AI service request timed out after 15 seconds. Please try again.');
      error.statusCode = 504;
      throw error;
    }

    // Re-throw handled errors with status codes
    if (err.statusCode) {
      throw err;
    }

    console.error('[Groq Unexpected Error]:', err.message);
    const error = new Error('Failed to generate study plan from AI service.');
    error.statusCode = 502;
    throw error;
  } finally {
    clearTimeout(timeoutId);
  }
};

/**
 * Orchestrates plan generation, switching between mock and Groq provider,
 * and performing full output validation before persistence.
 *
 * @param {object} params
 * @param {object} params.user - Authenticated user document
 * @param {object} params.goal - LearningGoal document
 * @returns {Promise<Array<object>>} Validated weeks array ready for LearningPlan persistence
 */
export const generatePlanWeeks = async ({ user, goal }) => {
  // 1. Find candidate catalog resources matching goal targetSkills
  const candidateResources = await findCandidateResources(goal);

  if (candidateResources.length === 0) {
    const error = new Error(
      'No relevant learning resources found matching your target skills. Please add target skills with available catalog resources.'
    );
    error.statusCode = 400;
    error.insufficientResources = true;
    throw error;
  }

  // 2. Fetch user's existing progress on candidate resources
  const progressMap = await getCandidateProgressMap(user._id, candidateResources);

  // 3. Determine provider (mock vs groq)
  const isTestEnv = process.env.NODE_ENV === 'test';
  const isExplicitGroq = process.env.AI_PROVIDER === 'groq';
  const isMockProvider = process.env.AI_PROVIDER === 'mock';
  const useMock = !isExplicitGroq && (isTestEnv || isMockProvider);

  // Strict check: In production, do not silently fall back to mock
  if (process.env.NODE_ENV === 'production' && !isMockProvider && !process.env.GROQ_API_KEY) {
    const error = new Error('AI provider configuration is missing on the server.');
    error.statusCode = 500;
    throw error;
  }

  let rawPlan;
  if (useMock) {
    rawPlan = generateDeterministicMockPlan({ goal, candidateResources, progressMap });
  } else {
    rawPlan = await callGroqApi({ goal, candidateResources, progressMap });
  }

  // 4. Treat all output as untrusted and validate strictly
  const validatedWeeks = validateAndSanitizeWeeks(rawPlan.weeks, candidateResources);

  return validatedWeeks;
};

export const aiService = {
  findCandidateResources,
  getCandidateProgressMap,
  validateAndSanitizeWeeks,
  generateDeterministicMockPlan,
  callGroqApi,
  generatePlanWeeks,
};
